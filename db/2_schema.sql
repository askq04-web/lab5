-- выполнить под postgres в базе lab_samples

CREATE TABLE users (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100) NOT NULL CHECK (trim(name) <> ''),
    email VARCHAR(100) UNIQUE
);

CREATE TABLE analysis_methods (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100)     NOT NULL UNIQUE CHECK (trim(name) <> ''),
    allowed_material VARCHAR(50)      NOT NULL CHECK (trim(allowed_material) <> ''),
    min_value        DOUBLE PRECISION NOT NULL,
    max_value        DOUBLE PRECISION NOT NULL,
    max_spread       DOUBLE PRECISION NOT NULL CHECK (max_spread >= 0),
    CHECK (min_value <= max_value)
);

CREATE TABLE samples (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material    VARCHAR(50) NOT NULL CHECK (trim(material) <> ''),
    customer_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    received_at TIMESTAMP   NOT NULL,
    status      VARCHAR(20) NOT NULL CHECK (status IN ('RECEIVED', 'IN_WORK', 'ANALYZED', 'ARCHIVED'))
);

CREATE TABLE analyses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id     BIGINT      NOT NULL REFERENCES samples (id) ON DELETE CASCADE,
    method_id     BIGINT      NOT NULL REFERENCES analysis_methods (id) ON DELETE RESTRICT,
    status        VARCHAR(20) NOT NULL CHECK (status IN ('NEW', 'IN_PROGRESS', 'COMPLETED')),
    average_value DOUBLE PRECISION,
    completed_at  TIMESTAMP,
    UNIQUE (sample_id, method_id),
    CHECK (status <> 'COMPLETED' OR (average_value IS NOT NULL AND completed_at IS NOT NULL))
);

CREATE TABLE measurements (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id BIGINT           NOT NULL REFERENCES analyses (id) ON DELETE CASCADE,
    value       DOUBLE PRECISION NOT NULL,
    measured_at TIMESTAMP        NOT NULL,
    confirmed   BOOLEAN          NOT NULL DEFAULT FALSE
);

GRANT CONNECT ON DATABASE lab_samples TO lab_app;
GRANT USAGE ON SCHEMA public TO lab_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO lab_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO lab_app;
